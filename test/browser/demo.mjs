import assert from 'node:assert/strict'
import {chromium} from 'playwright'

const base='http://127.0.0.1:4180'
const browser=await chromium.launch({channel:'chrome'})
async function typeSearch(page,name) {
 await page.getByRole('textbox',{name:'What are you shopping for?',exact:true}).fill(name)
 await page.getByRole('button',{name:'Find products for me'}).click()
 await page.getByRole('button',{name:'Skip and search',exact:true}).click()
}
try{
 const page=await browser.newPage({viewport:{width:1440,height:950}})
 const outside=[]
 page.on('request',request=>{if(!request.url().startsWith(base)||/\/api\/(listing|requirements)/.test(request.url())) outside.push(request.url())})
 await page.goto(base+'/demo.html')
 await typeSearch(page,'Body wash')
 await page.getByText('Choose a supported ZIP to see sample offers.').waitFor()
 for(const zip of ['92101','92037']){
   await page.getByRole('button',{name:zip,exact:true}).click()
   for(const name of ['Body wash','Face wash','Face moisturizer','Deodorant','Hand dish soap','Water bottle']){
     await typeSearch(page,name)
     assert.equal(await page.locator('.demo-card').count(),4,name+' '+await page.locator('#demo-results').innerText())
     assert.equal(await page.locator('.demo-card').getByText(/^Arrives /).count(),4)
   }
 }
 await page.getByLabel('ZIP code').fill('12345')
 await page.getByRole('button',{name:'Check delivery'}).click()
 await page.getByRole('alert').waitFor()
 assert.equal(await page.locator('.demo-card').count(),0)
 await page.evaluate(()=>localStorage.clear())
 await page.reload()
 await page.getByRole('button',{name:'92101',exact:true}).click()
 for(const [name,id] of [['Body wash','body-wash-1'],['Hand dish soap','dish-soap-2'],['Water bottle','bottle-2']]){
  await typeSearch(page,name)
  await page.locator('[data-offer="'+id+'"] button').click()
 }
 const total=()=>page.locator('[data-total]').getAttribute('data-total')
 assert.equal(await total(),'4346')
 const oldArrival=await page.locator('[data-row="bottle"]').getByText(/Arrives/).innerText()
 await page.getByRole('button',{name:'92037',exact:true}).click()
 assert.equal(await total(),'3247')
 assert.notEqual(await page.locator('[data-row="bottle"]').getByText(/Arrives/).innerText(),oldArrival)
 await page.getByRole('button',{name:'Choose a replacement'}).click()
 await page.locator('[data-offer="body-wash-2"] button').click()
 assert.equal(await total(),'4595')
 await page.getByRole('spinbutton',{name:'Packs for Body wash'}).fill('2')
 await page.getByRole('spinbutton',{name:'Packs for Body wash'}).press('Tab')
 assert.equal(await total(),'5444')
 await page.locator('[data-row="dish-soap"]').getByRole('button',{name:'Remove'}).click()
 assert.equal(await total(),'4895')
 assert.deepEqual(outside,[])
 console.log('Desktop: 4 listings × six presets × two ZIPs; three-category cart, ZIP replacement, packs, remove, zero external/provider calls')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:/View cart/}).click()
 await page.getByRole('complementary',{name:'Sample cart'}).waitFor()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.getByRole('button',{name:'Close',exact:true}).click()
 console.log('390 px: View cart opens and closes without overflow')
 const approval=await browser.newPage()
 await approval.goto(base+'/demo.html')
 await typeSearch(approval,'Body wash')
 await approval.getByRole('button',{name:'92101',exact:true}).click()
 await approval.locator('[data-offer="body-wash-1"] button').click()
 assert.equal(await approval.locator('[data-total]').getAttribute('data-total'),'1698')
 await approval.getByRole('button',{name:'Approve substitution'}).click()
 assert.equal(await approval.locator('[data-total]').getAttribute('data-total'),'1248')
 console.log('Sample substitution stayed unapplied until approval')
 const snapshot=await browser.newPage()
 await snapshot.goto(base)
 await snapshot.getByRole('button',{name:'Try a $37 shopping list'}).click()
 await snapshot.getByText('$40.17',{exact:true}).first().waitFor()
 await snapshot.getByText('$52.91',{exact:true}).first().waitFor()
 await snapshot.getByRole('button',{name:'Use recommended cart'}).click()
 await snapshot.getByRole('button',{name:'Approve size change'}).click()
 await snapshot.locator('.selection-total dd').getByText('$36.97',{exact:true}).waitFor()
 await snapshot.getByRole('link',{name:'Try the demo',exact:true}).click()
 await snapshot.getByRole('button',{name:'92101',exact:true}).click()
 await typeSearch(snapshot,'Deodorant')
 await snapshot.locator('[data-offer="deodorant-1"] button').click()
 await snapshot.getByRole('link',{name:'Live search',exact:true}).click()
 await snapshot.locator('.selection-total dd').getByText('$36.97',{exact:true}).waitFor()
 await snapshot.getByRole('link',{name:'Try the demo',exact:true}).click()
 await snapshot.locator('.sample-cart .cart-row').getByText(/Vanicream Anti-perspirant/).waitFor()
 console.log('Mode switch preserved both selected carts')
 console.log('Original snapshot: $40.17 vs. $52.91 → $36.97')
}finally{await browser.close()}
